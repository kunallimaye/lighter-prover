def tree_depth(n, radix):
  """ceil(log_radix(n)): number of node levels above N leaves.

  Mirrors `tree_depth` in bench/src/bin/prover_node.rs. Computed iteratively to
  avoid float rounding hazards near exact powers (e.g. log2(8) == 3 exactly).
  """
  if radix < 2:
    raise ValueError("radix must be >= 2")
  if n <= 1:
    return 0
  depth = 0
  span = 1  # radix**depth
  while span < n:
    span *= radix
    depth += 1
  return depth


def nodes_at_level(n, radix, level):
  """ceil(n / radix**level): node count at a 1-indexed tree level.

  Mirrors `nodes_at_level` in bench/src/bin/prover_node.rs. The root level always
  has exactly one node.
  """
  if level < 1:
    raise ValueError("tree levels are 1-indexed")
  divisor = radix ** level
  return max((n + divisor - 1) // divisor, 1)


def render_fungible(args, project_id, gsa_email, gcs_bucket, image_uri, leaf_chunk, default_cpu, default_mem):
  """Render the fungible-pool Deployment + KEDA ScaledObject (issue #302).

  This is the FUNGIBLE-AUTOSCALED path: one pod shape running
  `prover-node work --transport=pubsub`, scaled by KEDA on Pub/Sub backlog
  (baseload + burst, never scale-to-zero). It is distinct from the phase-locked
  per-level Indexed-Job path (#293/#297) emitted by the rest of this script.
  See infra-as-code/kubernetes/README.md for the comparison and ADR §4/§7.

  All cluster-applying actions are out of scope here; this only writes manifests.
  Live behavior (KEDA install, real backlog scaling, GKE scheduling) is
  TODO(confirm-on-live-run).
  """
  baseload = max(int(args.baseload), 1)  # never 0 — baseload is always-on (ADR §7)
  burst = max(int(args.burst), 0)
  max_replicas = baseload + burst
  arch = args.arch if args.arch else "c3d"
  # Use CLI override if present, else use default from config.toml
  cpu = args.cpu if args.cpu else default_cpu
  mem = args.memory if args.memory else default_mem
  topic = args.topic or "PLACEHOLDER_TOPIC"
  subscription = args.subscription or "PLACEHOLDER_SUBSCRIPTION"
  event_topic = args.event_topic or "PLACEHOLDER_EVENT_TOPIC"
  ack_deadline = int(args.ack_deadline)
  # terminationGracePeriod >= max prove time on target instance; sized for the
  # live 500-tx run's ≈80s radix-16 folds on c3d-highcpu-16 with comfortable
  # headroom (default ack_deadline 180s ⇒ grace 360s).
  grace = max(ack_deadline * 2, 120)

  deployment = f"""# Auto-generated by render_pod_spec.py --emit-fungible — do not edit by hand.
# Fungible-pool Deployment: autoscaled `prover-node work --transport=pubsub`.
# See infra-as-code/kubernetes/fungible_pool.yaml for the annotated template and
# docs/decisions/ADR-distributed-recursive-proving-architecture.md (§4, §7).
# TODO(confirm-on-live-run): live KEDA/GKE rollout + end-to-end proving.
apiVersion: v1
kind: ServiceAccount
metadata:
  name: prover-sa
  namespace: default
  annotations:
    iam.gke.io/gcp-service-account: {gsa_email or "GSA_EMAIL"}
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: lighter-fungible-prover
  labels:
    app: zkp-prover
    pool: fungible
    silicon-arch: {arch}
spec:
  replicas: {baseload}
  selector:
    matchLabels:
      app: zkp-prover
      pool: fungible
  template:
    metadata:
      annotations:
        gke-gcsfuse/volumes: "true"
        controller.kubernetes.io/pod-deletion-cost: "0"
      labels:
        app: zkp-prover
        pool: fungible
        role: fungible-worker
        silicon-arch: {arch}
    spec:
      serviceAccountName: prover-sa
      terminationGracePeriodSeconds: {grace}
      nodeSelector:
        role: fungible-worker
        silicon-arch: {arch}
      tolerations:
      - key: "dedicated"
        operator: "Equal"
        value: "zkp-prover"
        effect: "NoSchedule"
      - key: "cloud.google.com/gke-spot"
        operator: "Equal"
        value: "true"
        effect: "NoSchedule"
      containers:
      - name: prover
        image: {image_uri}
        command: ["prover-node", "work"]
        args:
        - "--transport=pubsub"
        - "--radix=$(RADIX)"
        - "--tx-per-proof=$(TX_PER_PROOF)"
        - "--ack-deadline=$(ACK_DEADLINE)"
        env:
        - name: PROVER_PUBSUB_PROJECT
          value: "{project_id}"
        - name: PROVER_PUBSUB_TOPIC
          value: "{topic}"
        - name: PROVER_PUBSUB_SUBSCRIPTION
          value: "{subscription}"
        - name: PROVER_PUBSUB_EVENT_TOPIC
          value: "{event_topic}"
        - name: PROVER_PUBSUB_BUCKET
          value: "{gcs_bucket}"
        - name: PROVER_PUBSUB_OBJECT_PREFIX
          value: ""
        - name: ACK_DEADLINE
          value: "{ack_deadline}"
        - name: RADIX
          value: "{args.radix}"
        - name: TX_PER_PROOF
          value: "{leaf_chunk}"
        - name: RUST_LOG
          value: "info"
        - name: RUST_MIN_STACK
          value: "4294967296"
        lifecycle:
          preStop:
            exec:
              command: ["/bin/sh", "-c", "sleep 1"]
        resources:
          requests:
            cpu: "{cpu}"
            memory: "{mem}"
          limits:
            cpu: "{cpu}"
            memory: "{mem}"
        volumeMounts:
        - name: gcs-volume
          mountPath: /data/reports/stark_proofs
      volumes:
      - name: gcs-volume
        csi:
          driver: gcsfuse.csi.storage.gke.io
          volumeAttributes:
            bucketName: "{gcs_bucket}"
            mountOptions: "implicit-dirs"
            metadataCacheTTLSeconds: "0"
            metadataStatCacheCapacity: "0"
"""

  scaledobject = f"""# Auto-generated by render_pod_spec.py --emit-fungible — do not edit by hand.
# KEDA ScaledObject: backlog autoscaling for the fungible pool. KEDA must be
# installed as a prerequisite (helm install keda kedacore/keda ...). NOT installed
# here. TODO(confirm-on-live-run): real backlog-driven scale up/down.
apiVersion: keda.sh/v1alpha1
kind: ScaledObject
metadata:
  name: lighter-fungible-prover
  labels:
    app: zkp-prover
    pool: fungible
spec:
  scaleTargetRef:
    apiVersion: apps/v1
    kind: Deployment
    name: lighter-fungible-prover
  minReplicaCount: {baseload}
  maxReplicaCount: {max_replicas}
  cooldownPeriod: 300
  pollingInterval: 15
  triggers:
  - type: gcp-pubsub
    metadata:
      mode: SubscriptionSize
      subscriptionName: "{subscription}"
      value: "1"
      activationValue: "0"
      projectID: "{project_id}"
  advanced:
    restoreToOriginalReplicaCount: false
    horizontalPodAutoscalerConfig:
      behavior:
        scaleDown:
          stabilizationWindowSeconds: 300
          policies:
          - type: Pods
            value: 1
            periodSeconds: 60
        scaleUp:
          stabilizationWindowSeconds: 0
          policies:
          - type: Pods
            value: 8
            periodSeconds: 30
"""

  dep_out = args.output.replace(".rendered.yaml", "-fungible.rendered.yaml")
  keda_out = args.output.replace(".rendered.yaml", "-fungible-keda.rendered.yaml")
  with open(dep_out, "w", encoding="utf-8") as f:
    f.write(deployment)
  with open(keda_out, "w", encoding="utf-8") as f:
    f.write(scaledobject)
  print(
      f"[OK] Rendered FUNGIBLE-pool manifests to {dep_out} (Deployment, "
      f"baseload={baseload} replicas) and {keda_out} (KEDA ScaledObject, "
      f"min={baseload}, max={max_replicas}, arch={arch}, radix={args.radix}, "
      f"ack_deadline={ack_deadline}s, grace={grace}s). "
      f"Live KEDA/GKE rollout is TODO(confirm-on-live-run)."
  )


